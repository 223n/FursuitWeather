// 定数・変換関数のテスト

import { describe, expect, it } from 'vitest';
import { weatherCodeLabel } from '../src/constants';

describe('weatherCodeLabel', () => {
  // WMOコードは連番ではなく歯抜けのため、範囲判定をテーブル化せずif連鎖で
  // 明示している（第1回レビューでの設計判断）。その守るべき振る舞い
  // （定義済みコードの分類と、歯抜けコードが「不明」になること）を固定する
  it.each([
    [0, '快晴'],
    [1, '晴れ'],
    [2, '一部曇り'],
    [3, '曇り'],
    [45, '霧'],
    [48, '霧'],
    [51, '霧雨'],
    [57, '霧雨'],
    [61, '雨'],
    [67, '雨'],
    [80, '雨'],
    [82, '雨'],
    [71, '雪'],
    [77, '雪'],
    [85, '雪'],
    [86, '雪'],
    [95, '雷雨'],
    [99, '雷雨'],
  ])('コード%iは「%s」', (code, label) => {
    expect(weatherCodeLabel(code)).toBe(label);
  });

  it.each([
    // -1は欠測時の内部既定値（pickHourが補完する値）
    [-1],
    // 各範囲の外側の隣接値。範囲を広げる退行（例: 78を雪扱い）を検出する
    [40],
    [50],
    [58],
    [60],
    [68],
    [78],
    [79],
    [83],
    [84],
    [87],
    [94],
  ])('未定義のコード%iは「不明」', (code) => {
    expect(weatherCodeLabel(code)).toBe('不明');
  });
});
